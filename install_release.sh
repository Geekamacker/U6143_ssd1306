#!/usr/bin/env bash
# Install or update this UCTRONICS fork from a verified GitHub Release.
# Run as a normal (sudo-capable) user, not as root.
set -euo pipefail

REPOSITORY="Geekamacker/U6143_ssd1306"
ARCHIVE_NAME="U6143_ssd1306-rpi.tar.gz"
API_BASE="https://api.github.com/repos/${REPOSITORY}"
DOWNLOAD_BASE="https://github.com/${REPOSITORY}/releases/download"

usage() {
    echo 'Usage: bash install_release.sh [--tag vX.Y.Z] [--no-install]'
    echo 'Without --tag, installs the latest non-prerelease GitHub Release.'
}

TAG=""
INSTALL=1
while (($#)); do
    case "$1" in
        --tag)
            if (($# < 2)); then usage >&2; exit 2; fi
            TAG="$2"
            shift 2
            ;;
        --no-install) INSTALL=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
done

if [[ $EUID -eq 0 ]]; then
    echo 'Run this installer as your normal user (it invokes sudo only when required).' >&2
    exit 1
fi
for command_name in curl python3 sha256sum tar mktemp; do
    command -v "$command_name" >/dev/null 2>&1 || {
        echo "Missing prerequisite: $command_name" >&2; exit 1;
    }
done

if [[ -z "$TAG" ]]; then
    echo "Finding latest release of ${REPOSITORY}..."
    if ! TAG=$(curl -fsSL --retry 3 -H 'Accept: application/vnd.github+json' \
        -H 'User-Agent: uctronics-release-installer' "${API_BASE}/releases/latest" | \
        python3 -c 'import sys,json; data=json.load(sys.stdin); print(data["tag_name"])'); then
        echo 'No latest release is accessible. Publish a non-prerelease GitHub Release first.' >&2
        exit 1
    fi
fi
if [[ ! "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+([.-][A-Za-z0-9.-]+)?$ ]]; then
    echo "Invalid or unsupported release tag: $TAG" >&2
    exit 1
fi

RELEASE_ROOT="${HOME}/.local/share/uctronics-display/releases"
mkdir -p "$RELEASE_ROOT"
TEMP_DIR=$(mktemp -d "$RELEASE_ROOT/.download.XXXXXXXX")
trap 'rm -rf -- "$TEMP_DIR"' EXIT

URL="${DOWNLOAD_BASE}/${TAG}/${ARCHIVE_NAME}"
echo "Downloading ${TAG} from GitHub Releases..."
curl -fsSL --retry 3 "$URL" -o "$TEMP_DIR/$ARCHIVE_NAME"
curl -fsSL --retry 3 "${URL}.sha256" -o "$TEMP_DIR/$ARCHIVE_NAME.sha256"
(
    cd "$TEMP_DIR"
    sha256sum -c "$ARCHIVE_NAME.sha256"
)

# This archive is generated by the repository's Actions workflow and has
# one fixed top-level folder; the following preflight rejects unusual entries.
python3 - "$TEMP_DIR/$ARCHIVE_NAME" <<'PY'
import pathlib, sys, tarfile
with tarfile.open(sys.argv[1], "r:gz") as tf:
    members = tf.getmembers()
    paths = [pathlib.PurePosixPath(m.name) for m in members]
    if not members or not any(str(p) == "U6143_ssd1306/setup_display_service.sh" for p in paths):
        sys.exit('Invalid release: missing setup_display_service.sh')
    for m, p in zip(members, paths):
        if p.is_absolute() or ".." in p.parts or p.parts[0] != "U6143_ssd1306":
            sys.exit(f'Unsafe archive path: {m.name}')
        if not (m.isfile() or m.isdir()):
            sys.exit(f'Unsupported archive entry type: {m.name}')
PY

tar -xzf "$TEMP_DIR/$ARCHIVE_NAME" -C "$TEMP_DIR"
DEST="$RELEASE_ROOT/$TAG"
if [[ -d "$DEST" ]]; then
    echo "Release ${TAG} already downloaded. Checking its recorded checksum..."
    CURRENT_HASH=$(sha256sum "$TEMP_DIR/$ARCHIVE_NAME" | cut -d' ' -f1)
    if [[ ! -f "$DEST/.release_sha256" ]] || [[ "$(cat "$DEST/.release_sha256")" != "$CURRENT_HASH" ]]; then
        echo "Existing $DEST has a different checksum. Leaving it untouched." >&2
        exit 1
    fi
else
    CURRENT_HASH=$(sha256sum "$TEMP_DIR/$ARCHIVE_NAME" | cut -d' ' -f1)
    printf '%s\n' "$CURRENT_HASH" > "$TEMP_DIR/U6143_ssd1306/.release_sha256"
    mv -- "$TEMP_DIR/U6143_ssd1306" "$DEST"
fi

if [[ "$INSTALL" == 0 ]]; then
    echo "Verified and extracted: $DEST"
    exit 0
fi

if ! command -v make >/dev/null 2>&1 || ! command -v gcc >/dev/null 2>&1; then
    echo 'Installing missing build-essential package...'
    sudo apt-get update
    sudo apt-get install -y build-essential
fi

echo "Installing UCTRONICS release ${TAG}..."
sudo UCTRONICS_ASSUME_YES=1 bash "$DEST/setup_display_service.sh"
echo
printf 'Installed release: %s\n' "$TAG"
printf 'Installed files: %s\n' "$DEST"
echo 'Your existing ~/U6143_ssd1306 Git clone was not modified.'
echo 'Check: systemctl status uctronics-display.service uctronics-boot-diagnostics.service'
